import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readAuth, type Auth } from "../step-auth.ts";
import {
    replaceCertificates,
    verifyCertificates,
} from "../step-certificates.ts";
import { credentialPath } from "../web-mounts.ts";
import type { ConfigurationService } from "./configuration.ts";
import { message } from "./errors.ts";

export type CredentialState = {
    generatedCertificates: boolean;
    secrets: Set<string>;
};
export type LogRedactionState = { pending: string; privateKey: boolean };
export class CredentialsService {
    private config: ConfigurationService;
    readonly shared: CredentialState;
    constructor(config: ConfigurationService, shared: CredentialState) {
        this.config = config;
        this.shared = shared;
    }
    read(): Auth {
        return readAuth(this.config.authPath);
    }
    mountedPath(path: string): string | null {
        const runtime = credentialPath(this.config.mounts, path);
        return runtime?.startsWith("/config/credentials/")
            ? join(
                  this.config.credentialsDirectory,
                  runtime.slice("/config/credentials/".length),
              )
            : runtime;
    }
    certificateState(auth = this.read()) {
        const certs = auth["suitecloud-certificates"];
        const generatedFilesExist = ["public.pem", "private.pem"].some((name) =>
            existsSync(join(this.config.credentialsDirectory, name)),
        );
        let error = "";
        let publicPath: string | null = null;
        let privatePath: string | null = null;
        if (certs?.public || certs?.private) {
            if (!certs.public || !certs.private)
                error =
                    "Set both certificate paths, or generate a new pair and register it on your scrumbox.";
            else {
                publicPath = this.mountedPath(certs.public);
                privatePath = this.mountedPath(certs.private);
                if (!publicPath || !privatePath)
                    error =
                        "Save credentials, stop the app, and run the launcher again to use these certificate files. You can also generate a new pair here.";
                else {
                    try {
                        verifyCertificates(publicPath, privatePath);
                    } catch (e) {
                        error = message(e);
                    }
                }
            }
        } else if (generatedFilesExist)
            error =
                "Certificate files already exist. Enter both paths in Certificate paths and save credentials, or generate and register a new pair.";
        else
            error =
                "Click Generate certificates, download and register the public certificate on your scrumbox, then enter its assigned certificate ID and save credentials.";
        return {
            hasExisting:
                generatedFilesExist || !!certs?.public || !!certs?.private,
            error,
            publicPath,
            privatePath,
        };
    }
    save(input: Record<string, unknown>): void {
        this.config.operations.assertIdle();
        const auth = this.read();
        if (input.token !== undefined) {
            if (typeof input.token !== "string" || /[\r\n\0]/.test(input.token))
                throw new Error("Enter a valid GitLab token.");
            if (input.token.trim()) auth["gitlab-token"] = input.token.trim();
        }
        const cert = auth["suitecloud-certificates"] ?? {
            public: "",
            private: "",
            id: "",
        };
        for (const key of ["public", "private", "id"] as const) {
            if (input[key] !== undefined) {
                if (
                    typeof input[key] !== "string" ||
                    /[\r\n\0,]/.test(input[key])
                )
                    throw new Error(
                        "Certificate settings must be single-line text.",
                    );
                cert[key] = input[key].trim();
            }
        }
        auth["suitecloud-certificates"] = cert;
        if (input.config !== undefined) this.config.save(input.config);
        this.write(auth);
    }
    write(auth: Auth): void {
        writeFileSync(
            this.config.authPath,
            JSON.stringify(auth, null, 4) + "\n",
            { mode: 0o600 },
        );
        chmodSync(this.config.authPath, 0o600);
        if (auth["gitlab-token"]) this.shared.secrets.add(auth["gitlab-token"]);
        if (auth.sftp?.password) this.shared.secrets.add(auth.sftp.password);
    }
    generate(replace: unknown): void {
        this.config.operations.assertIdle();
        if (this.certificateState().hasExisting && replace !== true)
            throw new Error(
                "Confirm replacement: old certificates generated by this app will not be preserved, and the saved certificate ID will be cleared.",
            );
        replaceCertificates(
            this.config.credentialsDirectory,
            this.config.authPath,
        );
        this.shared.generatedCertificates = true;
    }
    publicCertificate(): Uint8Array {
        const cert = this.certificateState();
        if (cert.error || !cert.publicPath)
            throw new Error(
                "A valid certificate pair is required before downloading.",
            );
        return new Uint8Array(readFileSync(cert.publicPath));
    }
    redact(text: string, streaming = false): string {
        try {
            const auth = this.read();
            if (auth["gitlab-token"])
                this.shared.secrets.add(auth["gitlab-token"]);
            if (auth.sftp?.password)
                this.shared.secrets.add(auth.sftp.password);
        } catch {
            /* Malformed credentials are reported by state. */
        }
        for (const secret of this.shared.secrets)
            if (secret) text = text.split(secret).join("[redacted]");
        text = text.replace(
            /-----BEGIN (?:RSA |EC |ENCRYPTED )?PRIVATE KEY-----[\s\S]*?(?:-----END (?:RSA |EC |ENCRYPTED )?PRIVATE KEY-----|$)/g,
            "[private key redacted]",
        );
        if (streaming) {
            // Withhold incomplete secret prefixes until the next chunk establishes their value.
            for (const secret of [...this.shared.secrets, "-----BEGIN "]) {
                for (
                    let n = Math.min(secret.length - 1, text.length);
                    n > 0;
                    n--
                ) {
                    if (text.endsWith(secret.slice(0, n))) {
                        text = text.slice(0, -n);
                        break;
                    }
                }
            }
        }
        return text;
    }
    redactChunk(
        state: LogRedactionState,
        chunk: string,
        final = false,
    ): string {
        let input = state.pending + chunk;
        state.pending = "";
        let output = "";
        const begins = [
            "-----BEGIN PRIVATE KEY-----",
            "-----BEGIN RSA PRIVATE KEY-----",
            "-----BEGIN EC PRIVATE KEY-----",
            "-----BEGIN ENCRYPTED PRIVATE KEY-----",
        ];
        while (input) {
            if (state.privateKey) {
                const end =
                    /-----END (?:RSA |EC |ENCRYPTED )?PRIVATE KEY-----/.exec(
                        input,
                    );
                if (!end) {
                    if (!final) state.pending = input.slice(-80);
                    return output;
                }
                input = input.slice(end.index + end[0].length);
                state.privateKey = false;
                continue;
            }
            const begin =
                /-----BEGIN (?:RSA |EC |ENCRYPTED )?PRIVATE KEY-----/.exec(
                    input,
                );
            if (begin) {
                output +=
                    this.redact(input.slice(0, begin.index)) +
                    "[private key redacted]";
                input = input.slice(begin.index + begin[0].length);
                state.privateKey = true;
                continue;
            }
            this.redact(""); // Refresh saved secrets before determining a safe chunk boundary.
            let withheld = 0;
            for (const secret of [...this.shared.secrets, ...begins]) {
                for (
                    let size = Math.min(secret.length - 1, input.length);
                    size > withheld;
                    size--
                )
                    if (input.endsWith(secret.slice(0, size))) {
                        withheld = size;
                        break;
                    }
            }
            const safe = withheld ? input.slice(0, -withheld) : input;
            output += this.redact(safe);
            if (withheld) {
                if (final) output += "[redacted]";
                else state.pending = input.slice(-withheld);
            }
            break;
        }
        return output;
    }
}
